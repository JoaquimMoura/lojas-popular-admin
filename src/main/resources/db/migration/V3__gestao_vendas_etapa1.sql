-- ---------------------------------------------------------------------------
-- Reserva de estoque (criada na confirmação da venda)
-- ---------------------------------------------------------------------------
CREATE TABLE public.reservas_estoque (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id bigint NOT NULL REFERENCES public.pedidos (id),
    item_id bigint NOT NULL REFERENCES public.itens_pedido (id),
    produto_id bigint NOT NULL REFERENCES public.produtos (id),
    variacao_id bigint REFERENCES public.produto_variacoes (id),
    quantidade integer NOT NULL,
    status character varying(20) NOT NULL,
    criada_em timestamp(6) with time zone NOT NULL,
    liberada_em timestamp(6) with time zone,
    motivo_liberacao character varying(300),
    CONSTRAINT reservas_estoque_status_check CHECK (status IN ('ATIVA', 'LIBERADA', 'CONSUMIDA')),
    CONSTRAINT reservas_estoque_quantidade_check CHECK (quantidade > 0)
);
CREATE INDEX idx_reservas_pedido ON public.reservas_estoque (pedido_id);
CREATE INDEX idx_reservas_produto_status ON public.reservas_estoque (produto_id, status);
CREATE INDEX idx_reservas_variacao_status ON public.reservas_estoque (variacao_id, status);
-- No máximo uma reserva ativa por item (a confirmação não pode duplicar reservas).
CREATE UNIQUE INDEX uk_reserva_ativa_item ON public.reservas_estoque (item_id) WHERE status = 'ATIVA';
