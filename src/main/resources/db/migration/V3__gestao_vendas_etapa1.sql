-- Mapa de conversão explícito dos pedidos antigos (sem presumir cliente, vendedor,
-- reserva, comissão ou quitação):
--   PAGO      -> pagamento quitado
--   ENTREGUE  -> entrega concluída (não presume quitação)
--   CANCELADO -> cancelada
--   CRIADO    -> exige revisão
UPDATE public.pedidos SET status_pagamento = 'PAGO'     WHERE status = 'PAGO';
UPDATE public.pedidos SET status_entrega   = 'ENTREGUE' WHERE status = 'ENTREGUE';
UPDATE public.pedidos SET status_comercial = 'CANCELADA' WHERE status = 'CANCELADO';
UPDATE public.pedidos SET revisao_legado = true WHERE status = 'CRIADO';

