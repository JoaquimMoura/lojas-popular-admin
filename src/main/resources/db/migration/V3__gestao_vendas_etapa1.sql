-- ---------------------------------------------------------------------------
-- Clientes (pessoa física)
-- ---------------------------------------------------------------------------
CREATE TABLE public.clientes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL DEFAULT 0,
    nome character varying(150) NOT NULL,
    cpf character varying(11),
    telefone character varying(20),
    email character varying(150),
    observacoes character varying(500),
    ativo boolean NOT NULL DEFAULT true,
    criado_em timestamp(6) with time zone NOT NULL,
    atualizado_em timestamp(6) with time zone
);
CREATE UNIQUE INDEX uk_clientes_cpf ON public.clientes (cpf) WHERE cpf IS NOT NULL;
CREATE INDEX idx_clientes_telefone ON public.clientes (telefone);
CREATE INDEX idx_clientes_nome ON public.clientes (lower(nome));

CREATE TABLE public.enderecos_cliente (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id bigint NOT NULL REFERENCES public.clientes (id),
    apelido character varying(60),
    cep character varying(8),
    logradouro character varying(150) NOT NULL,
    numero character varying(20),
    complemento character varying(100),
    bairro character varying(100),
    cidade character varying(100) NOT NULL,
    uf character varying(2) NOT NULL,
    principal boolean NOT NULL DEFAULT false
);
CREATE INDEX idx_enderecos_cliente ON public.enderecos_cliente (cliente_id);

-- ---------------------------------------------------------------------------
-- Configuração comercial (linha única, id = 1). Campos nulos = decisão pendente.
-- ---------------------------------------------------------------------------
CREATE TABLE public.configuracao_comercial (
    id bigint PRIMARY KEY,
    limite_desconto_percentual numeric(5,2),          -- D03
    arredondamento character varying(20),             -- D04
    perfis_cancelamento character varying(100),       -- D07 (lista separada por vírgula)
    atualizado_em timestamp(6) with time zone,
    atualizado_por bigint REFERENCES public.users (id),
    CONSTRAINT configuracao_comercial_arred_check
        CHECK (arredondamento IS NULL OR arredondamento IN ('HALF_UP', 'HALF_EVEN', 'DOWN', 'UP')),
    CONSTRAINT configuracao_comercial_limite_check
        CHECK (limite_desconto_percentual IS NULL OR (limite_desconto_percentual >= 0 AND limite_desconto_percentual <= 100))
);

CREATE TABLE public.condicoes_pagamento (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    forma character varying(20) NOT NULL,
    parcelas integer NOT NULL,
    ajuste_percentual numeric(7,2) NOT NULL,          -- acréscimo (+) ou desconto (-) sobre o preço base
    ativa boolean NOT NULL DEFAULT true,
    CONSTRAINT condicoes_pagamento_forma_check CHECK (forma IN ('DINHEIRO', 'PIX', 'CARTAO')),
    CONSTRAINT condicoes_pagamento_parcelas_check CHECK (parcelas >= 1),
    CONSTRAINT uk_condicao_forma_parcelas UNIQUE (forma, parcelas)
);

